"""Interaction checks. Usage: python3 tests/interactions.py"""
import os, sys
from playwright.sync_api import sync_playwright
URL = 'file://' + os.path.abspath('index.html')
fails = []
def check(name, cond):
    print(('PASS ' if cond else 'FAIL ') + name)
    if not cond: fails.append(name)

with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    ctx = b.new_context(viewport={'width': 390, 'height': 800})
    pg = ctx.new_page(); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(URL)
    check('default language is Bangla', pg.evaluate("document.documentElement.lang") == 'bn')
    check('hero Bangla headline', 'আবহাওয়া বদলাচ্ছে' in pg.inner_text('h1'))
    pg.click('#lang-en')
    check('switch to English without reload', 'weather is changing' in pg.inner_text('h1'))
    pg.reload()
    check('language persists after reload', pg.evaluate("document.documentElement.lang") == 'en')
    pg.click('#lang-bn')
    pg.select_option('#sel-district', 'rajshahi'); pg.select_option('#sel-crop', 'mustard')
    check('summary updates (bn)', 'রাজশাহী' in pg.inner_text('#dash-summary') and 'সরিষা' in pg.inner_text('#dash-summary'))
    pg.reload()
    check('selection persists', pg.input_value('#sel-district') == 'rajshahi')
    check('menu closed initially', not pg.is_visible('#site-nav'))
    pg.click('#menu-btn'); check('menu opens on mobile', pg.is_visible('#site-nav'))
    pg.keyboard.press('Escape'); check('Escape closes menu', not pg.is_visible('#site-nav'))
    check('no speech synthesis in code', pg.evaluate("!document.documentElement.innerHTML.includes('speechSynthesis')"))

    # ---- Milestone 2: climate explorer ----
    pg.evaluate("localStorage.clear()"); pg.reload()
    t1 = pg.inner_text('#climate-cards')
    pg.select_option('#sel-district', 'rajshahi')
    t2 = pg.inner_text('#climate-cards')
    check('district change updates climate cards', t1 != t2 and '২৬.৩' in t2)
    check('Rajshahi hot days (41) shown in Bangla digits', '৪১' in t2)
    pg.select_option('#sel-crop', 'wheat')
    check('crop change updates planting window chart', 'গম' in pg.inner_text('#ch-win-cap'))
    check('five charts rendered', pg.locator('#climate-shift figure.chart').count() == 6)
    pg.click('#lang-en')
    en = pg.inner_text('#climate-cards')
    check('English mode uses Latin digits and no Bengali digits', '26.3' in en and not any(c in en for c in '০১২৩৪৫৬৭৮৯'))
    check('English chart titles', 'Rainfall by month' in pg.inner_text('#ch-rain-cap'))
    keys = pg.evaluate("[Object.keys(SC._strings.bn).filter(k=>!(k in SC._strings.en)), Object.keys(SC._strings.en).filter(k=>!(k in SC._strings.bn))]")
    check('translation key parity bn/en', keys == [[], []])
    pg.click('#lang-bn')
    bn_text = pg.inner_text('main')
    check('Bangla mode shows no Latin digits in numbers', not __import__('re').search('[0-9]', bn_text))

    # ---- Milestone 3: crop rotation explorer ----
    pg.evaluate("localStorage.clear()"); pg.reload()
    check('three rotation cards', pg.locator('#rot-cards article.rot-card').count() == 3)
    check('no fit shown without priorities', 'এখনো কোনো অগ্রাধিকার' in pg.inner_text('#rot-fit'))
    pg.click('[data-prio="water"]')
    check('priority toggles aria-pressed', pg.get_attribute('[data-prio="water"]', 'aria-pressed') == 'true')
    f1 = pg.inner_text('#rot-fit')
    pg.click('[data-prio="income"]')
    f2 = pg.inner_text('#rot-fit')
    check('changing priorities updates the comparison', f1 != f2 and 'ডেমো স্কোর' in f2)
    check('focus stays on toggled chip', pg.evaluate("document.activeElement.getAttribute('data-prio')") == 'income')
    pg.reload()
    check('priorities persist', pg.get_attribute('[data-prio="income"]', 'aria-pressed') == 'true')
    c1 = pg.inner_text('#rot-cards')
    pg.select_option('#sel-crop', 'mung')
    check('crop change updates rotation sequences', c1 != pg.inner_text('#rot-cards'))
    check('comparison table has 3 strategy columns', pg.locator('#rot-table thead th').count() == 4)
    pg.click('[data-why="water"]')
    check('explanation switches strategy', 'কম পানির ফসলে' in pg.inner_text('#rot-why'))
    check('expert-review notice visible', 'বিশেষজ্ঞ' in pg.inner_text('#rot-why'))
    pg.click('#lang-en')
    check('rotation fully English', 'Water-conscious rotation' in pg.inner_text('#rot-cards') and not __import__('re').search('[\u0980-\u09FF]', pg.inner_text('#rotation')))
    pg.click('#lang-bn')
    check('no JS errors', not errs)
    b.close()
sys.exit(1 if fails else 0)
